// Schemas
const UserSchema = new mongoose.Schema({
  name: String, email: String, password: String, role: String, phone: String, bio: String,
  regNo: String, department: String, hostelBlock: String, studentCategory: String,
  phoneVerified: Boolean, isComplimentaryApproved: Boolean,
  preferredSports: [String], favorites: [{ type: mongoose.Schema.Types.ObjectId, ref: "Facility" }],
  status: String, createdAt: Date,
});

const FacilitySchema = new mongoose.Schema({
  name: String, type: String, location: String, campusLocation: String, city: String, description: String,
  capacity: Number, openingTime: String, closingTime: String, pricePerHour: Number,
  indoorOutdoor: String, surfaceType: String, amenities: [String], rules: [String],
  equipmentAvailable: [String], image: String, status: String, cancellationHours: Number,
  featured: Boolean, bookingCount: Number,
  publishedQuantity: Number, verifiedQuantity: Number, isQuantityVerified: Boolean,
  discrepancyNote: String, sourceUrl: String, lastVerificationDate: Date,
  bookingEligibility: [String], membershipRequired: Boolean, approvalRequired: Boolean,
  requiresCoachSupervision: Boolean, maintenanceStatus: String,
  createdAt: Date,
});

const MembershipPlanSchema = new mongoose.Schema({
  sportCategory: String, sessionYear: String, description: String,
  hostellerEdbFee: Number, hostellerRegularFee: Number, dayScholarFee: Number,
  isSwimmingPlan: Boolean, hourlyRateHosteller: Number, hourlyRateDayScholar: Number,
  monthlyRateHosteller: Number, monthlyRateDayScholar: Number, semesterRateHosteller: Number,
  semesterRateDayScholar: Number, registrationFee: Number, monthlyCoachingFee: Number,
  sourceUrl: String, isActive: Boolean, createdAt: Date, updatedAt: Date,
});

const MembershipSchema = new mongoose.Schema({
  userId: mongoose.Schema.Types.ObjectId, planId: mongoose.Schema.Types.ObjectId,
  sportCategory: String, sessionYear: String, studentCategory: String, regNo: String,
  applicableFee: Number, isComplimentary: Boolean, complimentaryApprovedBy: mongoose.Schema.Types.ObjectId,
  complimentaryReason: String, status: String, paymentStatus: String, paymentReference: String,
  startDate: Date, expiryDate: Date, approvedBy: mongoose.Schema.Types.ObjectId, approvedAt: Date,
  notes: String, createdAt: Date,
});

const SwimmingSlotSchema = new mongoose.Schema({
  facilityId: mongoose.Schema.Types.ObjectId, date: String, startTime: String, endTime: String,
  category: String, maxCapacity: Number, bookedCount: Number, isOpen: Boolean,
  isCoachSupervised: Boolean, coachName: String, notes: String, createdAt: Date,
});

const BookingSchema = new mongoose.Schema({
  bookingReference: String, userId: mongoose.Schema.Types.ObjectId, facilityId: mongoose.Schema.Types.ObjectId,
  date: String, startTime: String, endTime: String, durationHours: Number, pricePerHour: Number,
  studentCategory: String, regNo: String, approvalRequired: Boolean, approvalStatus: String,
  approvedBy: mongoose.Schema.Types.ObjectId, approvedByName: String, approvalNotes: String, approvedAt: Date,
  equipmentAddons: [{ equipmentId: mongoose.Schema.Types.ObjectId, name: String, quantity: Number, price: Number }],
  equipmentTotal: Number, totalPrice: Number, paymentMethod: String, paymentStatus: String,
  paymentDetails: Object, status: String, qrCodeToken: String, isAttended: Boolean, attendedAt: Date,
  attendanceVerifiedBy: mongoose.Schema.Types.ObjectId, isSwimmingSlot: Boolean, swimmingCategory: String,
  notes: String, cancellationReason: String, cancelledAt: Date, createdAt: Date,
});

const EquipmentSchema = new mongoose.Schema({
  name: String, sportCategory: String, description: String, image: String,
  totalQuantity: Number, availableQuantity: Number, issuedQuantity: Number,
  damagedQuantity: Number, underMaintenanceQuantity: Number, condition: String,
  rentalEligibility: String, rentalFee: Number, securityDeposit: Number, storeLocation: String,
  isProposedCatalog: Boolean, sourceNote: String, status: String, createdAt: Date, updatedAt: Date,
});

const EquipmentCheckoutSchema = new mongoose.Schema({
  userId: mongoose.Schema.Types.ObjectId, equipmentId: mongoose.Schema.Types.ObjectId,
  bookingId: mongoose.Schema.Types.ObjectId, quantity: Number, checkoutTime: Date,
  expectedReturnTime: Date, actualReturnTime: Date, status: String, returnCondition: String,
  managerNotes: String, issuedBy: mongoose.Schema.Types.ObjectId, receivedBy: mongoose.Schema.Types.ObjectId,
  rentalFeePaid: Number, securityDepositHeld: Number, depositRefunded: Boolean, createdAt: Date,
});

const MaintenanceSchema = new mongoose.Schema({
  facilityId: mongoose.Schema.Types.ObjectId, date: String, startTime: String, endTime: String,
  reason: String, status: String, createdAt: Date,
});

const SystemRuleSchema = new mongoose.Schema({
  key: String, maxActiveBookingsPerUser: Number, maxAdvanceBookingDays: Number,
  maxBookingDurationHours: Number, cancellationDeadlineHours: Number,
  primeTimeStart: String, primeTimeEnd: String, maxPrimeTimeBookingsPerWeek: Number,
  allowWaitlist: Boolean, updatedAt: Date,
});

const NotificationSchema = new mongoose.Schema({
  userId: mongoose.Schema.Types.ObjectId, title: String, message: String,
  type: String, read: Boolean, referenceId: String, createdAt: Date,
});

const AuditLogSchema = new mongoose.Schema({
  action: String, performedBy: mongoose.Schema.Types.ObjectId, performedByName: String,
  entityType: String, entityId: String, details: String, severity: String, createdAt: Date,
});

const User = mongoose.model("User", UserSchema);
const Facility = mongoose.model("Facility", FacilitySchema);
const MembershipPlan = mongoose.model("MembershipPlan", MembershipPlanSchema);
const Membership = mongoose.model("Membership", MembershipSchema);
const SwimmingSlot = mongoose.model("SwimmingSlot", SwimmingSlotSchema);
const Booking = mongoose.model("Booking", BookingSchema);
const Equipment = mongoose.model("Equipment", EquipmentSchema);
const EquipmentCheckout = mongoose.model("EquipmentCheckout", EquipmentCheckoutSchema);
const Maintenance = mongoose.model("Maintenance", MaintenanceSchema);
const SystemRule = mongoose.model("SystemRule", SystemRuleSchema);
const Notification = mongoose.model("Notification", NotificationSchema);
const AuditLog = mongoose.model("AuditLog", AuditLogSchema);

function daysFromNow(n) {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString().split("T")[0];
}

